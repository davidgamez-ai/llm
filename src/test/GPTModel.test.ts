import { test } from "node:test";
import assert from "node:assert/strict";
import Hyperparameters from "../Hyperparameters.js";
import GPTModel from "../GPTModel.js";

/*
 * Reference logits: a safety net for refactoring.
 *
 * A tiny seeded model is run on a fixed token sequence in each mode, and its
 * logits are compared with values recorded before the training code was
 * added. Any change to the forward pass, including a change to the order in
 * which dropout draws its random numbers, makes this test fail.
 *
 * Each row of logits is vocabularySize (50,257) values wide, which is too
 * many to store, so each row is summarized by its sum, its sum of squares and
 * the values at a few fixed indices. A change anywhere in the row almost
 * certainly changes the sum of squares.
 *
 * If the forward pass is changed on purpose, the reference values must be
 * regenerated by printing summarize(model.update(TOKENS)) for each mode.
 */

/** The vocabulary indices whose logits are recorded. */
const INDICES: number[] = [0, 1, 2, 1000, 25000, 50256];

/** The token ids fed into the model. Token 3290 appears twice, to include a repeated token. */
const TOKENS: number[] = [464, 3290, 318, 3290];

/**
 * The largest difference allowed between a recorded value and a new one.
 * Small enough that only a harmless reordering of floating-point additions
 * could pass, not a real change to the calculation.
 */
const TOLERANCE: number = 1e-12;

/** A summary of one row of logits. */
interface RowSummary {
  sum: number;
  sumOfSquares: number;
  samples: number[];
}

/**
 * Summarizes each row of logits by its sum, sum of squares and the values at INDICES.
 *
 * @param logits - One row of logits per token.
 * @returns One summary per row.
 */
const summarize = (logits: number[][]): RowSummary[] =>
  logits.map((row) => ({
    sum: row.reduce((sum, value) => sum + value, 0),
    sumOfSquares: row.reduce((sum, value) => sum + value * value, 0),
    samples: INDICES.map((index) => row[index]),
  }));

/**
 * Builds the tiny model (embeddingSize 8, 2 heads, 1 block, contextLength 4,
 * seed 42) in the given mode and runs it on TOKENS.
 *
 * @param mode - TRAINING_MODE, VALIDATION_MODE or GENERATION_MODE.
 * @returns The summarized logits.
 */
const run = (mode: number): RowSummary[] => {
  const hyperparameters = new Hyperparameters(8, 4, 0.1, mode, 2, 1, 3);
  hyperparameters.seed = 42;
  return summarize(new GPTModel(hyperparameters).update(TOKENS));
};

/**
 * Asserts that two lists of row summaries match to within TOLERANCE.
 *
 * @param actual - The summaries from the current code.
 * @param expected - The recorded summaries.
 */
const assertMatches = (actual: RowSummary[], expected: RowSummary[]): void => {
  assert.equal(actual.length, expected.length, "number of rows");
  for (let row = 0; row < expected.length; row++) {
    const pairs: [string, number, number][] = [
      ["sum", actual[row].sum, expected[row].sum],
      ["sumOfSquares", actual[row].sumOfSquares, expected[row].sumOfSquares],
      ...expected[row].samples.map((value, i): [string, number, number] =>
        [`logit ${INDICES[i]}`, actual[row].samples[i], value]),
    ];
    for (const [name, actualValue, expectedValue] of pairs) {
      assert.ok(
        Math.abs(actualValue - expectedValue) <= TOLERANCE,
        `Row ${row}, ${name}: expected ${expectedValue}, got ${actualValue}`
      );
    }
  }
};

